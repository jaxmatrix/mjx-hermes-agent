#!/usr/bin/env node
/**
 * Which gateway RPCs take a `profile` param, read off the backend's wire contract.
 *
 * `tui_gateway/contracts` is the source of truth; `scripts/gen_gateway_contracts.py`
 * renders it to `apps/shared/src/gateway-contract.openrpc.json`. Params models
 * are `extra="forbid"`, so a `profile` on a method that does not declare one
 * answers `4000` — `HermesGateway` (`src/hermes.ts`) has to know the difference
 * at runtime, and the 800 KB contract cannot ship in the bundle. This renders
 * the two method lists it needs.
 *
 *   node scripts/gen-gateway-profile-methods.mjs
 *
 * `src/transport/gateway-profile-methods.test.ts` re-derives both lists from the
 * contract and fails when the committed module is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const APP_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const CONTRACT = resolve(APP_DIR, '../shared/src/gateway-contract.openrpc.json')
const OUT = resolve(APP_DIR, 'src/transport/gateway-profile-methods.generated.ts')

const contract = JSON.parse(readFileSync(CONTRACT, 'utf8'))
const scoped = []
const unscoped = []

for (const method of contract.methods) {
  const ref = method.params?.[0]?.schema?.$ref
  const schema = typeof ref === 'string' ? contract.components.schemas[ref.split('/').pop()] : undefined

  // The Python generator flattens inherited fields into `properties`. Any other
  // shape means this reader is out of date, not that the method is unscoped.
  if (method.params?.length !== 1 || schema?.type !== 'object') {
    throw new Error(`${method.name}: params are not a single object schema`)
  }

  ;(Object.hasOwn(schema.properties ?? {}, 'profile') ? scoped : unscoped).push(method.name)
}

const list = names =>
  names
    .sort()
    .map(name => `  '${name}'`)
    .join(',\n')

writeFileSync(
  OUT,
  `// GENERATED by scripts/gen-gateway-profile-methods.mjs from
// apps/shared/src/gateway-contract.openrpc.json — DO NOT EDIT.
// Regenerate: node scripts/gen-gateway-profile-methods.mjs
// src/transport/gateway-profile-methods.test.ts fails when this file is stale.

/** Methods whose params declare \`profile\`. */
export const PROFILE_METHODS: ReadonlySet<string> = new Set([
${list(scoped)}
])

/** Methods whose params do not: a \`profile\` on one answers \`4000\`. */
export const UNSCOPED_METHODS: ReadonlySet<string> = new Set([
${list(unscoped)}
])
`
)
